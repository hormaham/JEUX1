function basic(L, op) {
  let a, b, r;
  const span = [[1, 10], [10, 99], [100, 999], [1000, 9999], [10000, 999999]];
  if (op === "+") { a = rd(L, span); b = rd(L, span); r = a + b; }
  else if (op === "−") { const m = [[1, 20], ...span.slice(1)]; a = rd(L, m); b = rd(L, m); if (b > a) [a, b] = [b, a]; r = a - b; }
  else if (op === "×") { const [x, y] = at(L, [[[1, 5], [1, 10]], [[2, 12], [2, 12]], [[11, 99], [3, 9]], [[12, 99], [12, 99]], [[112, 999], [112, 999]]]); a = R(...x); b = R(...y); r = a * b; }
  else { const [d, q] = at(L, [[[1, 5], [1, 10]], [[2, 12], [2, 12]], [[3, 15], [11, 40]], [[12, 60], [21, 99]], [[23, 99], [112, 999]]]); b = R(...d); r = R(...q); a = b * r; }
  const check = op === "−" ? S("نتحقق بالعملية العكسية", r, "+", b, "=", a)
    : op === "÷" ? S("نتحقق بالعملية العكسية", r, "×", b, "=", a)
    : S("النتيجة", a, op, b, "=", r);
  return Q([a, op, b], r, [check]);
}
