function basic(level, op) {
  const i = level - 1; let a, b, r;
  if (op === "+") { const [l, h] = [[1, 10], [10, 99], [100, 999]][i]; a = R(l, h); b = R(l, h); r = a + b; }
  else if (op === "−") { const [l, h] = [[1, 20], [10, 99], [100, 999]][i]; a = R(l, h); b = R(l, h); if (b > a) [a, b] = [b, a]; r = a - b; }
  else if (op === "×") { const [x, y] = [[[1, 5], [1, 10]], [[2, 12], [2, 12]], [[11, 99], [3, 9]]][i]; a = R(...x); b = R(...y); r = a * b; }
  else { const [d, q] = [[[1, 5], [1, 10]], [[2, 12], [2, 12]], [[3, 15], [11, 40]]][i]; b = R(...d); r = R(...q); a = b * r; }
  const check = op === "−" ? S("نتحقق بالعملية العكسية", r, "+", b, "=", a)
    : op === "÷" ? S("نتحقق بالعملية العكسية", r, "×", b, "=", a)
    : S("النتيجة", a, op, b, "=", r);
  return Q([a, op, b], r, [check]);
}
